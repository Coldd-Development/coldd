-- Agency admin section, real data (replaces the sample document in agency_data).
-- Devs, leads, commissions, client payments, dev assignments and notes. Every
-- table is admin-only (RLS public.is_admin()). Services, trailer packages and
-- the "Taking work" switches stay in agency_data id = 'settings'.

create table if not exists public.agency_devs (
  id uuid primary key default gen_random_uuid(),
  name text not null check (length(name) between 1 and 60),
  skills text[] not null default '{}',
  status text not null default 'candidate' check (status in ('team', 'candidate')),
  rate text check (rate is null or length(rate) <= 80),
  pay_method text check (pay_method is null or length(pay_method) <= 40),
  created_at timestamptz not null default now()
);

create table if not exists public.agency_leads (
  id uuid primary key default gen_random_uuid(),
  num bigint generated by default as identity (start with 101),
  title text not null check (length(title) between 1 and 120),
  client text check (client is null or length(client) <= 80),
  source text not null default 'discord' check (source in ('bbb', 'discord', 'x', 'site', 'other')),
  service text not null check (length(service) between 1 and 40),
  budget text check (budget is null or length(budget) <= 60),
  budget_usd numeric(10, 2) check (budget_usd is null or budget_usd >= 0),
  wants_by text check (wants_by is null or length(wants_by) <= 60),
  details text check (details is null or length(details) <= 2000),
  existing_game text check (existing_game is null or length(existing_game) <= 120),
  refs text check (refs is null or length(refs) <= 500),
  status text not null default 'new' check (status in ('new', 'replied', 'consultation', 'converted', 'declined')),
  consultation_at timestamptz,
  replied_at timestamptz,
  commission_id uuid,
  created_at timestamptz not null default now()
);

create table if not exists public.agency_commissions (
  id uuid primary key default gen_random_uuid(),
  num bigint generated by default as identity (start with 1001),
  title text not null check (length(title) between 1 and 120),
  client text check (client is null or length(client) <= 80),
  service text not null check (length(service) between 1 and 40),
  source text not null default 'discord' check (source in ('bbb', 'discord', 'x', 'site', 'other')),
  price_usd numeric(10, 2) not null default 0 check (price_usd >= 0),
  stage smallint not null default 0 check (stage between 0 and 3),
  due_on date,
  brief text check (brief is null or length(brief) <= 4000),
  thread_url text check (thread_url is null or (length(thread_url) <= 500 and thread_url ~* '^https?://')),
  lead_id uuid references public.agency_leads (id) on delete set null,
  delivered_at timestamptz,
  created_at timestamptz not null default now()
);

do $$ begin
  alter table public.agency_leads add constraint agency_leads_commission_fk
    foreign key (commission_id) references public.agency_commissions (id) on delete set null;
exception when duplicate_object then null;
end $$;

-- Money the client paid us for a commission.
create table if not exists public.agency_payments (
  id uuid primary key default gen_random_uuid(),
  commission_id uuid not null references public.agency_commissions (id) on delete cascade,
  amount_usd numeric(10, 2) not null check (amount_usd > 0),
  paid_on date not null default current_date,
  note text check (note is null or length(note) <= 200),
  created_at timestamptz not null default now()
);

-- A dev's part of a commission and what we pay them for it.
create table if not exists public.agency_assignments (
  id uuid primary key default gen_random_uuid(),
  commission_id uuid not null references public.agency_commissions (id) on delete cascade,
  dev_id uuid not null references public.agency_devs (id) on delete restrict,
  part text check (part is null or length(part) <= 80),
  cost_usd numeric(10, 2) not null default 0 check (cost_usd >= 0),
  cost_robux integer not null default 0 check (cost_robux >= 0),
  paid_at timestamptz,
  created_at timestamptz not null default now()
);

create table if not exists public.agency_notes (
  id uuid primary key default gen_random_uuid(),
  commission_id uuid not null references public.agency_commissions (id) on delete cascade,
  body text not null check (length(body) between 1 and 1000),
  created_by uuid default auth.uid(),
  created_by_name text check (created_by_name is null or length(created_by_name) <= 80),
  created_at timestamptz not null default now()
);

create index if not exists agency_payments_commission_idx on public.agency_payments (commission_id);
create index if not exists agency_assignments_commission_idx on public.agency_assignments (commission_id);
create index if not exists agency_assignments_dev_idx on public.agency_assignments (dev_id);
create index if not exists agency_notes_commission_idx on public.agency_notes (commission_id, created_at desc);
create index if not exists agency_leads_status_idx on public.agency_leads (status, created_at desc);

do $$
declare t text;
begin
  foreach t in array array['agency_devs', 'agency_leads', 'agency_commissions', 'agency_payments', 'agency_assignments', 'agency_notes'] loop
    execute format('alter table public.%I enable row level security', t);
    begin
      execute format('create policy %I on public.%I for all using (public.is_admin()) with check (public.is_admin())', t || '_admin_all', t);
    exception when duplicate_object then null;
    end;
    execute format('revoke all on public.%I from anon, authenticated', t);
    execute format('grant select, insert, update, delete on public.%I to authenticated', t);
  end loop;
end $$;
